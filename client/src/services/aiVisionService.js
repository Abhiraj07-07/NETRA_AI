// AI Vision Service: Multimodal Scene & Object Description for Visually Impaired Users
// Supports:
// 1. Built-in Local AI Object & Saliency Summarizer (100% Offline, Zero Key Required)
// 2. Google Gemini 1.5/2.0 Flash Multimodal Vision API (Deep natural language Hindi description)

import { speechService } from './speechService';
import { visionDetector } from './visionDetector';

class AIVisionService {
  constructor() {
    this.geminiApiKey = typeof window !== 'undefined' ? (localStorage.getItem('netra_gemini_api_key') || '') : '';
    this.isAnalyzing = false;
    this.lastDescription = '';
  }

  setApiKey(key) {
    this.geminiApiKey = (key || '').trim();
    if (typeof window !== 'undefined') {
      localStorage.setItem('netra_gemini_api_key', this.geminiApiKey);
    }
  }

  getApiKey() {
    return this.geminiApiKey;
  }

  hasApiKey() {
    return !!this.geminiApiKey && this.geminiApiKey.length > 10;
  }

  // Capture canvas as base64 JPEG
  getCanvasBase64(canvas) {
    if (!canvas) return null;
    try {
      const dataUrl = canvas.toDataURL('image/jpeg', 0.8);
      return dataUrl.split(',')[1]; // Strip "data:image/jpeg;base64," prefix
    } catch (e) {
      console.warn('Canvas export error:', e);
      return null;
    }
  }

  // ===============================================================
  // 1. GOOGLE GEMINI FLASH MULTIMODAL VISION API
  // ===============================================================
  async describeWithGemini(base64Image) {
    if (!this.hasApiKey()) return null;

    const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${this.geminiApiKey}`;

    const promptText = `You are NETRA AI, an assistive vision companion for a blind person in India. 
Look at this camera image and describe in 2 short, crisp sentences in conversational Hindi (or Hinglish):
1. What key objects, furniture, people, or obstacles are directly in front of the user and their positions (left, center, right).
2. Approximate distance (in meters or steps) and whether the walking pathway ahead is clear or blocked.
Keep the description very practical and safety-focused. Do not mention that this is an image.`;

    const requestBody = {
      contents: [
        {
          parts: [
            { text: promptText },
            {
              inlineData: {
                mimeType: "image/jpeg",
                data: base64Image
              }
            }
          ]
        }
      ],
      generationConfig: {
        temperature: 0.3,
        maxOutputTokens: 150
      }
    };

    const response = await fetch(endpoint, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(requestBody)
    });

    if (!response.ok) {
      const errData = await response.json().catch(() => ({}));
      throw new Error(errData?.error?.message || `Gemini API error: ${response.status}`);
    }

    const data = await response.json();
    const candidate = data.candidates?.[0]?.content?.parts?.[0]?.text;
    if (!candidate) throw new Error('No description generated by Gemini AI');

    return candidate.trim();
  }

  // ===============================================================
  // 2. BUILT-IN OFFLINE AI SCENE SUMMARIZER (Zero Setup, 100% Free)
  // ===============================================================
  // Uses detected neural/heuristic bounding boxes, skin clusters, and wall depth
  async describeWithBuiltInAI(canvas) {
    if (!canvas) return "कैमरा व्यू तैयार नहीं है। कृपया कैमरा ऑन करें।";

    const detected = await visionDetector.detectObjects(canvas);
    const { width, height } = canvas;

    if (!detected || detected.length === 0) {
      return "Pathway is completely clear ahead. Samne ka rasta saaf hai.";
    }

    // Separate walls and objects
    const walls = detected.filter(d => d.isWall || d.class === 'wall');
    const objects = detected.filter(d => !d.isWall && d.class !== 'wall');

    const descriptions = [];

    // 1. Wall alert if present
    if (walls.length > 0) {
      const w = walls[0];
      const posLabel = w.direction === 'left' ? 'on left' : w.direction === 'right' ? 'on right' : 'ahead';
      const posHindi = w.direction === 'left' ? 'left taraf' : w.direction === 'right' ? 'right taraf' : 'samne';
      const dist = typeof w.distance === 'number' ? `${w.distance} meters` : (w.distance || '1 meter');
      descriptions.push(`Wall ${posLabel} at ${dist}. ${posHindi} deewar hai.`);
    }

    // 2. Group everyday objects by direction
    const centerObjects = [];
    const leftObjects = [];
    const rightObjects = [];

    objects.forEach(obj => {
      const centerX = obj.bbox[0] + obj.bbox[2] / 2;
      const ratio = centerX / (width || 640);
      const name = this.translateObjectName(obj.class || obj.label || 'obstacle');
      const dist = typeof obj.distance === 'number' ? `${obj.distance}m` : '';
      const formatted = dist ? `${name} (${dist})` : name;

      if (ratio < 0.35) {
        leftObjects.push(formatted);
      } else if (ratio > 0.65) {
        rightObjects.push(formatted);
      } else {
        centerObjects.push(formatted);
      }
    });

    if (centerObjects.length > 0) {
      descriptions.push(`Ahead: ${[...new Set(centerObjects)].join(', ')}. Samne dikh raha hai.`);
    }
    if (leftObjects.length > 0) {
      descriptions.push(`On left: ${[...new Set(leftObjects)].join(', ')}. Left taraf hai.`);
    }
    if (rightObjects.length > 0) {
      descriptions.push(`On right: ${[...new Set(rightObjects)].join(', ')}. Right taraf hai.`);
    }

    // Pathway assessment
    if (centerObjects.length === 0 && walls.filter(w => w.direction === 'center').length === 0) {
      descriptions.push("Pathway is clear to walk forward. Rasta saaf hai.");
    } else {
      descriptions.push("Please walk carefully. Savdhaan rahein.");
    }

    return descriptions.join(' ');
  }

  // Friendly names for common objects
  translateObjectName(engName) {
    const map = {
      person: 'Person (vyakti)',
      chair: 'Chair (kursi)',
      couch: 'Sofa',
      table: 'Table (mez)',
      desk: 'Desk',
      bottle: 'Bottle (botal)',
      cup: 'Cup',
      'cell phone': 'Mobile phone',
      cell_phone: 'Mobile phone',
      phone: 'Mobile phone',
      laptop: 'Laptop',
      backpack: 'Bag',
      handbag: 'Handbag',
      door: 'Door (darwaza)',
      stairs: 'Stairs (seedhiyan)',
      bed: 'Bed',
      tv: 'TV',
      car: 'Car (gaadi)',
      motorcycle: 'Motorcycle (bike)',
      bicycle: 'Bicycle (cycle)',
      dog: 'Dog (kutta)',
      cat: 'Cat (billi)',
      wall: 'Wall (deewar)',
      obstacle: 'Obstacle (rukawat)'
    };
    return map[(engName || '').toLowerCase()] || engName;
  }

  // Shortcut alias for describeScene
  async describeScene(canvas) {
    const res = await this.analyzeAndDescribeScene(canvas);
    return {
      description: res?.text || "Pathway is clear ahead.",
      spokenText: res?.text || "Pathway is clear ahead."
    };
  }

  // ===============================================================
  // 3. MASTER SCENE ANALYZER & ANNOUNCER
  // ===============================================================
  async analyzeAndDescribeScene(canvas, { onStatusUpdate = () => {} } = {}) {
    if (this.isAnalyzing) return;
    this.isAnalyzing = true;

    try {
      let finalDescription = '';
      let isGeminiUsed = false;

      // Check if Gemini API Key is configured
      if (this.hasApiKey()) {
        onStatusUpdate('Google Gemini AI दृश्य का विश्लेषण कर रहा है...');
        speechService.speak("AI scene analyzing...", { priority: true });
        
        const base64Img = this.getCanvasBase64(canvas);
        if (base64Img) {
          try {
            finalDescription = await this.describeWithGemini(base64Img);
            isGeminiUsed = true;
          } catch (geminiErr) {
            console.warn('Gemini vision API error, falling back to local AI:', geminiErr);
            onStatusUpdate('Gemini fallback to local AI...');
          }
        }
      }

      // If Gemini wasn't used or failed, use built-in offline engine
      if (!finalDescription) {
        onStatusUpdate('लोकल AI इंजन से वस्तुओं की पहचान की जा रही है...');
        finalDescription = await this.describeWithBuiltInAI(canvas);
      }

      this.lastDescription = finalDescription;
      onStatusUpdate(finalDescription);

      // Speak result out loud
      speechService.speak(finalDescription, { priority: true });

      return {
        text: finalDescription,
        engine: isGeminiUsed ? 'Gemini 1.5 Flash Vision' : 'Built-in Local AI'
      };
    } catch (err) {
      console.error('Scene analysis failed:', err);
      const fallbackMsg = "सामने वस्तुओं की पहचान में त्रुटि हुई। कृपया दोबारा प्रयास करें।";
      speechService.speak(fallbackMsg, { priority: true });
      return { text: fallbackMsg, engine: 'Error' };
    } finally {
      this.isAnalyzing = false;
    }
  }
}

export const aiVisionService = new AIVisionService();
